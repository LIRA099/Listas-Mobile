public class Exercicio02Arrays {
    public static void main(String[] args) {

        String[] animais = {
                "Cachorro",
                "Gato",
                "Leão",
                "Cavalo",
                "Capivara"
        };

        System.out.println("Animais:");

        for (String animal : animais) {
            System.out.println(animal);
        }
    }
}